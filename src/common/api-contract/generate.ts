import { interventionForArtisan, interventionForBoard, interventionForClient, interventionForRoom, interventionForTracking } from '../views/views';
import { ParsedSchema, parsePrismaSchema } from './prisma-schema';
import { Node, mergeNodes, nodeOfRow, renderNode } from './shape';
import { VARIANTS, buildRow } from './synthetic';

/**
 * The files of the shared package that come from the server (P1-09).
 *
 * Nothing here is written by hand in the package: the page and error types, the status table and the
 * table of trades are copied as they are, the enums are read off the schema, and the type of each job a reader may
 * receive is read off the real views. `npm run contract:generate` writes them into
 * ../smart-depannage-shared/src/generated; `npm run contract:check` fails when they are out of date.
 */

export const HEADER = [
  '/*',
  ' * GENERATED by smart-depannage-serveur: `npm run contract:generate`.',
  ' * Do not edit this file here or in an app: change the server, then generate again.',
  ' */',
  '',
].join('\n');

/** Where the files that are copied as they are live in the server, and what they are called in the package. */
export const COPIED_FILES: Array<{ from: string; to: string }> = [
  { from: 'src/common/api-contract/envelope.ts', to: 'envelope.ts' },
  { from: 'src/modules/intervention-workflow/intervention-status.ts', to: 'intervention-status.ts' },
  // The trades (P1-10): the apps list them in their forms, and the table is the same one the server reads.
  { from: 'src/common/trades/trades.ts', to: 'trades.ts' },
  // Who opens which page of the dashboard, and who sees which button (P1-12): the menu and the route guard read it.
  { from: 'src/common/auth/staff-pages.ts', to: 'staff-pages.ts' },
];

export const SCHEMA_FILE = 'prisma/schema.prisma';

interface ViewSpec {
  name: string;
  doc: string;
  view: (row: any) => any;
}

/** The jobs a reader may receive, and the view that makes each. */
export const JOB_VIEWS: ViewSpec[] = [
  { name: 'ClientIntervention', doc: 'A job as the signed-in customer who owns it receives it.', view: interventionForClient },
  { name: 'TrackingIntervention', doc: 'A job as the visitor who holds the tracking link receives it.', view: interventionForTracking },
  { name: 'ArtisanIntervention', doc: 'A job as the artisan who has it receives it.', view: interventionForArtisan },
  { name: 'BoardIntervention', doc: 'A job as an artisan sees it on the board of open jobs.', view: interventionForBoard },
  { name: 'RoomIntervention', doc: 'A job as everybody in its live room receives it.', view: interventionForRoom },
];

const pascal = (key: string) => key.charAt(0).toUpperCase() + key.slice(1);

/** events -> event: the name of one element of a list. */
const singular = (key: string) => (key.endsWith('s') ? key.slice(0, -1) : key);

/** The files that the schema gives: one union type and one list of values for each enum. */
export function enumsFile(schema: ParsedSchema): string {
  const blocks = Object.entries(schema.enums).map(([name, values]) => {
    const list = values.map((value) => `'${value}'`).join(', ');

    return `export const ${name}Values = [${list}] as const;\nexport type ${name} = (typeof ${name}Values)[number];\n`;
  });

  return `${HEADER}\n${blocks.join('\n')}`;
}

/** The type of what one view answers for a job: its columns, and the relations a route may include. */
function jobType(spec: ViewSpec, schema: ParsedSchema): { named: string[]; text: string } {
  const nodes: Node[] = VARIANTS.map((variant) => nodeOfRow(spec.view(buildRow(schema, 'Intervention', 2, variant)), 'Intervention', schema));
  const job = nodes.reduce(mergeNodes);

  if (job.k !== 'obj') throw new Error(`${spec.name}: the view did not answer an object`);

  // A relation of the job gets a name of its own, so an app can write ClientInterventionPayment.
  const named: string[] = [];
  const lines: string[] = [];

  for (const [key, prop] of job.props) {
    const node = prop.node;
    let type: string;
    const listed = node.k === 'arr' && node.item;
    const element = node.k === 'arr' ? node.item : node;
    const hoistable = (n: Node | null): n is Extract<Node, { k: 'obj' }> => n !== null && n.k === 'obj';

    if (prop.optional && hoistable(element) && element.props.size) {
      const alias = `${spec.name}${pascal(listed ? singular(key) : key)}`;

      named.push(`export type ${alias} = ${renderNode(element)};\n`);
      type = listed ? `${alias}[]` : alias;
    } else if (prop.optional && node.k === 'union' && node.of.some((part) => hoistable(part) && part.props.size)) {
      const objects = node.of.filter((part): part is Extract<Node, { k: 'obj' }> => hoistable(part));
      const alias = `${spec.name}${pascal(key)}`;

      named.push(`export type ${alias} = ${renderNode((objects as Node[]).reduce(mergeNodes))};\n`);
      type = [alias, ...node.of.filter((part) => !hoistable(part)).map((part) => renderNode(part, 1))].join(' | ');
    } else {
      type = renderNode(node, 1);
    }

    lines.push(`  ${/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key)}${prop.optional ? '?' : ''}: ${type};`);
  }

  return { named, text: `/** ${spec.doc} */\nexport type ${spec.name} = {\n${lines.join('\n')}\n};\n` };
}

export function viewsFile(schema: ParsedSchema): string {
  const enumNames = Object.keys(schema.enums);
  const parts = JOB_VIEWS.map((spec) => jobType(spec, schema));
  const body = parts.map((part) => [...part.named, part.text].join('\n')).join('\n');
  const used = enumNames.filter((name) => new RegExp(`\\b${name}\\b`).test(body));

  return [
    HEADER,
    `import type { ${used.join(', ')} } from './enums';`,
    '',
    'export type JsonValue = string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue };',
    '',
    body,
  ].join('\n');
}

/** Every generated file, by its name inside the package's src/generated folder. */
export function generateContract(read: (relativePath: string) => string): Record<string, string> {
  const schema = parsePrismaSchema(read(SCHEMA_FILE));
  const files: Record<string, string> = {};

  for (const copied of COPIED_FILES) {
    files[copied.to] = `${HEADER}${read(copied.from)}`;
  }

  files['enums.ts'] = enumsFile(schema);
  files['views.ts'] = viewsFile(schema);
  files['index.ts'] = [
    HEADER,
    "export * from './envelope';",
    "export * from './intervention-status';",
    "export * from './staff-pages';",
    "export * from './trades';",
    "export * from './views';",
    "export * as Enums from './enums';",
    '',
  ].join('\n');

  return files;
}

/**
 * What is wrong with the generated folder of the shared package, one line per file: a file that is
 * missing, one that is out of date, and one that is left over (nothing generates it any more, but
 * the package may still import it). Empty when the folder is exactly what the server generates.
 * Line endings do not count (a checkout on Windows).
 */
export function contractDrift(generated: Record<string, string>, onDisk: Record<string, string>): string[] {
  const plain = (text: string) => text.replace(/\r\n/g, '\n');
  const problems: string[] = [];

  for (const [name, text] of Object.entries(generated)) {
    if (!Object.prototype.hasOwnProperty.call(onDisk, name)) {
      problems.push(`${name}: missing`);
    } else if (plain(onDisk[name]) !== plain(text)) {
      problems.push(`${name}: out of date`);
    }
  }

  for (const name of Object.keys(onDisk)) {
    if (!Object.prototype.hasOwnProperty.call(generated, name)) {
      problems.push(`${name}: left over (nothing generates it any more)`);
    }
  }

  return problems;
}
